package com.kert0n.medapp.presentation.value

/**
 * Какая единица **обычно** у этой формы выпуска: таблетки и капсулы считают штуками, сироп и
 * капли — миллилитрами, мазь — граммами, аэрозоль — дозами.
 *
 * Это подсказка ввода, а не правило домена: домен принимает любую единицу с любой формой, и
 * человек вправе поставить свою — редкие лекарства меряют не так, как принято (PLAN H1: разбор и
 * удобство ввода живут у представления).
 *
 * Сопоставление идёт **по имени словаря**: идентификаторы у каждого сервера свои, а имена форм и
 * единиц приходят из одного и того же словаря. Незнакомая форма не подставляет ничего —
 * выдуманная единица хуже пустого поля.
 */
fun FormPresentationDTO.usualUnit(units: List<UnitPresentationDTO>): UnitPresentationDTO? {
    val wanted = USUAL[name.trim().lowercase()] ?: return null
    return units.firstOrNull { it.name.trim().lowercase() == wanted }
}

/**
 * Пары, о которых можно сказать уверенно. Спорное сюда не попадает: порошок бывает и в граммах, и
 * в саше, концентрат — и в миллилитрах, и в ампулах, а «другие» не значит ничего.
 */
private val USUAL: Map<String, String> = mapOf(
    "таблетки" to "шт",
    "капсулы" to "шт",
    "суппозитории" to "шт",
    "раствор" to "мл",
    "сироп" to "мл",
    "суспензия" to "мл",
    "настойка" to "мл",
    "капли" to "мл",
    "гель" to "г",
    "мазь" to "г",
    "крем" to "г",
    "аэрозоль" to "доз",
    "спрей" to "доз"
)
