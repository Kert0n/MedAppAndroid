package com.kert0n.medapp.presentation.plan

import com.kert0n.medapp.domain.intake.IntakeRejected
import com.kert0n.medapp.presentation.value.QuantityPresentationDTO
import java.time.LocalDate
import java.time.LocalTime
import kotlin.uuid.Uuid

/**
 * Страница дня глазами экрана (PLAN H3 «Набор приёмов и истории», экран 12).
 *
 * Страница названа **сдвигом**, а не датой: сдвиг человек и выбирает, листая вперёд, а дата у того
 * же сдвига в полночь становится другой. Оба поля здесь, потому что заголовку нужны оба — число и
 * слово «сегодня»/«завтра», которое считается по сдвигу.
 *
 * Пункты разложены по тому, что с ними можно делать. [items] — записанные календарём: на них
 * отвечают. [alsoOnThisDay] — разовые приёмы этого дня и пункты за окном календаря: они уже
 * случились или ещё не записаны, и действий у них нет (H3). Деление — здесь, а не в вёрстке: куда
 * попадёт строка, решает её состояние.
 */
data class DayPagePresentationDTO(
    val date: LocalDate,
    val daysAhead: Int,
    val items: List<DayItemPresentationDTO>,
    val alsoOnThisDay: List<DayItemPresentationDTO>,
    /**
     * О чём не смогли напомнить: обязательства, которые приложение не сказало вовремя — телефон
     * молчал, а человек пришёл сам (PLAN D8, H3 «Уведомления на экране»). Отвечают на них теми же
     * двумя кнопками: отдельного листа для этого не заводится.
     */
    val unannounced: List<DayItemPresentationDTO> = emptyList(),
    /** Чем кончился ответ, если по самой странице этого не видно (PLAN U1). */
    val message: DayMessage? = null
) {
    val isEmpty: Boolean get() = items.isEmpty() && alsoOnThisDay.isEmpty() && unannounced.isEmpty()
}

/**
 * Что мешает приложению напомнить вовремя (PLAN H3 «Уведомления на экране»).
 *
 * Оба случая разные, и говорят о них по-разному: без разрешения приложение немо вовсе, а с
 * неточным будильником оно скажет — но позже. Молчать о втором нельзя: человек решит, что
 * напоминание потерялось, хотя это система отложила его ради батареи.
 */
data class DayPermissionsPresentationDTO(
    val notificationsOff: Boolean = false,
    val alarmsInexact: Boolean = false
) {
    val isQuiet: Boolean get() = !notificationsOff && !alarmsInexact
}

/**
 * Что страница отвечает на ответ, когда записать его не вышло. Записанное своего случая здесь не
 * имеет: о нём говорит сама строка, а молчание после «принял» человек и так читает как успех.
 */
sealed interface DayMessage {

    /** Домен отверг приём: причина по месту — в коробке не набралось, единица не та, эпизод закрыт. */
    data class Refused(val reason: IntakeRejected.Reason) : DayMessage

    /** Пункт уже отвечен: страница перечитает, а решение человек повторит, если хотел другого. */
    data object AlreadyAnswered : DayMessage

    /** Лечение кончилось, пока человек отвечал: план ответов больше не принимает (D6). */
    data object EpisodeClosed : DayMessage

    /** Пункта больше нет: расписание перестроили, и строка уйдёт со страницы вместе с чтением. */
    data object Gone : DayMessage
}

/**
 * Строка дня: во сколько, что, сколько, откуда и чем кончилось.
 *
 * [title] называет то, о чём строка: у пункта курса — лечение, у разового приёма — коробку, из
 * которой человек взял: лечения за ним нет, и придумывать его нечем. [dose] и [packageName] —
 * **фактические**, когда факт есть, и плановые, пока его нет: строка отвечает на вопрос «что со
 * мной было», а не «что мне назначали».
 *
 * [answeredAt] — время ответа: «принят 09:12» человек читает вместе с самим словом. У
 * неотвеченного его нет.
 */
data class DayItemPresentationDTO(
    val intakeId: Uuid?,
    val courseId: Uuid?,
    val title: String,
    /** День пункта, когда он не сегодняшний: у вчерашнего обязательства время без дня немо. */
    val on: LocalDate? = null,
    val at: LocalTime,
    val dose: QuantityPresentationDTO,
    val packageName: String?,
    val state: State,
    val answeredAt: LocalTime?,
    /** Есть ли у пункта плановая пачка: без неё быстрый ответ брать неоткуда (PLAN D5). */
    val hasPlannedPackage: Boolean = false,
    val isAnswering: Boolean = false
) {

    /**
     * Можно ли ещё подтвердить приём **быстро**. Пропущенный — можно: доза уехала вперёд, и
     * подтвердить её позже законно (PLAN D6, решение владельца 2026-09-16). А вот пункт без
     * плановой пачки — нельзя: брать неоткуда, и коробку человек выбирает на карточке; кнопка,
     * которая ничего не делает, хуже её отсутствия.
     *
     * Идущая запись ([isAnswering]) действие не отменяет, а гасит: исчезнувшая кнопка читалась бы
     * как «уже ответил», а её и не было.
     */
    val canConfirm: Boolean
        get() = hasPlannedPackage && (state == State.PLANNED || state == State.MISSED)

    /** Отказаться можно от того, на что ещё не ответили: пропущенное уже пропущено. */
    val canDecline: Boolean get() = state == State.PLANNED

    /**
     * Показывать ли, что записано. У ждущего пункта записывать нечего, а у остальных — есть, и
     * пропущенный говорит об этом **вместе** с кнопкой «Принял»: иначе отказ выглядел бы так же,
     * как молчание, и человек не узнал бы, что его услышали (найдено историей Анны).
     */
    val tellsItsState: Boolean get() = state != State.PLANNED


    /**
     * Что со строкой, глазами человека. Значений шесть, а не «статус плюс вид»: человек видит
     * одно слово на строку, и «ожидается» с «разовым» стоят в том же ряду, что «принят» и
     * «пропущен», — они различают строки так же, как и остальные.
     */
    enum class State {

        /** Пункт ждёт ответа. */
        PLANNED,

        /** Принят: есть количество, пачка и момент. */
        TAKEN,

        /** Не принят — отказался или не ответил; доза уехала вперёд, и подтвердить её ещё можно. */
        MISSED,

        /** Пункт отменён вместе с лечением. */
        CANCELLED,

        /** Доза этого дня, которую календарь ещё не записал: показать можно, отвечать не на что. */
        EXPECTED,

        /** Разовый приём: случился мимо всякого лечения. */
        ONE_OFF
    }
}
