package com.kert0n.medapp.presentation.plan

import com.kert0n.medapp.presentation.value.QuantityPresentationDTO
import java.time.LocalDate
import java.time.LocalTime
import kotlin.uuid.Uuid

/**
 * Страница дня глазами экрана (PLAN H3 «Набор приёмов и истории», экран 12).
 *
 * Страница названа **сдвигом**, а не датой: сдвиг человек и выбирает, листая вперёд, а дата у того
 * же сдвига в полночь становится другой. Оба поля здесь, потому что заголовку нужны оба — число и
 * слово «сегодня»/«завтра», которое считается по сдвигу.
 *
 * Пункты разложены по тому, что с ними можно делать. [items] — записанные календарём: на них
 * отвечают. [alsoOnThisDay] — разовые приёмы этого дня и пункты за окном календаря: они уже
 * случились или ещё не записаны, и действий у них нет (H3). Деление — здесь, а не в вёрстке: куда
 * попадёт строка, решает её состояние.
 */
data class DayPagePresentationDTO(
    val date: LocalDate,
    val daysAhead: Int,
    val items: List<DayItemPresentationDTO>,
    val alsoOnThisDay: List<DayItemPresentationDTO>
) {
    val isEmpty: Boolean get() = items.isEmpty() && alsoOnThisDay.isEmpty()
}

/**
 * Строка дня: во сколько, что, сколько, откуда и чем кончилось.
 *
 * [title] называет то, о чём строка: у пункта курса — лечение, у разового приёма — коробку, из
 * которой человек взял: лечения за ним нет, и придумывать его нечем. [dose] и [packageName] —
 * **фактические**, когда факт есть, и плановые, пока его нет: строка отвечает на вопрос «что со
 * мной было», а не «что мне назначали».
 *
 * [answeredAt] — время ответа: «принят 09:12» человек читает вместе с самим словом. У
 * неотвеченного его нет.
 */
data class DayItemPresentationDTO(
    val intakeId: Uuid?,
    val courseId: Uuid?,
    val title: String,
    val at: LocalTime,
    val dose: QuantityPresentationDTO,
    val packageName: String?,
    val state: State,
    val answeredAt: LocalTime?,
    val isAnswering: Boolean = false
) {

    /**
     * Есть ли на что отвечать в строке. Пропущенному отвечают тоже: доза уехала вперёд, и
     * подтвердить её позже законно (PLAN D6, решение владельца 2026-09-16).
     *
     * Идущая запись ([isAnswering]) действие не отменяет, а гасит: исчезнувшая кнопка читалась бы
     * как «уже ответил», а её и не было.
     */
    val canAnswer: Boolean get() = state == State.PLANNED || state == State.MISSED


    /**
     * Что со строкой, глазами человека. Значений шесть, а не «статус плюс вид»: человек видит
     * одно слово на строку, и «ожидается» с «разовым» стоят в том же ряду, что «принят» и
     * «пропущен», — они различают строки так же, как и остальные.
     */
    enum class State {

        /** Пункт ждёт ответа. */
        PLANNED,

        /** Принят: есть количество, пачка и момент. */
        TAKEN,

        /** Не принят — отказался или не ответил; доза уехала вперёд, и подтвердить её ещё можно. */
        MISSED,

        /** Пункт отменён вместе с лечением. */
        CANCELLED,

        /** Доза этого дня, которую календарь ещё не записал: показать можно, отвечать не на что. */
        EXPECTED,

        /** Разовый приём: случился мимо всякого лечения. */
        ONE_OFF
    }
}
