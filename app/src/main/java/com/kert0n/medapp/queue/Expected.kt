package com.kert0n.medapp.queue

/**
 * Какой формы квитанцию ждёт поручение — по контракту той операции, в которую оно превращается
 * (PLAN B4, B5). Проверяет форму курьер ([Courier.Pass.read]): квитанция не по форме — исход
 * неизвестен, и поручение повторяется тем же запросом.
 */
enum class Expected {

    /** Тело обязательно: снимок пачки. Пустое тело — сбой протокола. */
    SNAPSHOT,

    /** Снимок пачки либо ноль байтов — пачка израсходована и уничтожена (B5). */
    SNAPSHOT_OR_GONE,

    /** Бронь: `{drugId, amount}` без версии картины (B6) — снимок читается следом. */
    CLAIM,

    /** Тела не ждут: `204`, либо тело, которое команде не нужно. */
    NOTHING
}
