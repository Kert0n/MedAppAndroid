package com.kert0n.medapp.queue

import java.time.Instant

/**
 * Что осталось в очереди после захода и когда за ним приходить. Нужно тому, кто планирует заход
 * без живого процесса (PLAN E4): в процессе сроки держит `QueueOutbox`, а после его смерти — только
 * планировщик системы, и сказать ему «не нужно» или «вот когда» может только база.
 *
 * Порт узок настолько, насколько нужен: планировщику не нужны ни строки, ни их порядок.
 */
interface QueueBacklog {

    /** `null` — незакрытых операций нет. Иначе — ближайший срок; прошедший значит «как будет связь». */
    suspend fun dueAt(now: Instant): Instant?
}
