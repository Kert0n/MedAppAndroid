package com.kert0n.medapp.queue

import java.time.Instant

/**
 * Заходы без человека: система поднимает процесс, когда пора, и координатор синхронизации делает
 * то же, что при входе в приложение (PLAN E4). Выполняет порт платформа — очередь не знает, кто
 * будит процесс.
 */
interface SyncSchedule {

    /**
     * Регулярный заход раз в [interval]. Тот же интервал ничего не пересоздаёт; другой — обновляет
     * ту же задачу, а не ставит вторую рядом (PLAN E4).
     */
    suspend fun keepRegular(interval: SyncInterval)

    /**
     * В очереди осталось неотправленное: зайти не раньше [dueAt] и только при связи. Заход ставится,
     * даже если процесс умрёт, — иначе принятое в метро ждало бы, пока человек снова откроет приложение.
     */
    fun comeBackFor(dueAt: Instant)
}
