package com.kert0n.medapp.queue

/**
 * Что значит 404 для команды: у каждой — своё, потому что 404 отвечают разные ресурсы (PLAN
 * B4, E3). Пачки нет — доступа к ней нет; своей брони нет, где её правят или снимают, — желаемое
 * состояние готовится заново либо уже наступило; удаляемой пачки нет — она уже удалена; полки, в
 * которую кладут коробку, нет — класть некуда, и это отказ, а не конец коробки: сама коробка у
 * человека в руках (PLAN E6).
 */
enum class NotFoundPolicy { ACCESS_LOST, REPREPARE, APPLIED, REFUSE }
