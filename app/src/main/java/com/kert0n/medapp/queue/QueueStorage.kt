package com.kert0n.medapp.queue

import com.kert0n.medapp.domain.medkit.MedKitRef
import com.kert0n.medapp.queue.pack.PackageSnapshot
import java.time.Instant
import kotlin.uuid.Uuid
import kotlinx.coroutines.flow.Flow

/**
 * Что очереди нужно от хранилища — и только это: прочитать и записать операцию, положить снимок,
 * применить решённый исход. Что делать, решает очередь; хранение пишет решённое. Взятие в отправку
 * — одна транзакция, которую открывает работник ([Transactions]): свежий снимок, подготовка по
 * нему и заморозка запроса ложатся вместе (PLAN F5). Реализация живёт в хранении.
 */
interface QueueStorage {

    /**
     * Сигнал «таблица операций изменилась» — после коммита по определению: тот, кто положил
     * команду, о ней не сообщает, её замечает тот, кто следит за таблицей ([QueueOutbox]). Первое
     * значение — «наблюдатель встал», не изменение ([OutboxLoop]).
     */
    fun changes(): Flow<Unit>

    /**
     * Готовые к работе на момент [now], по порядку номера — одно определение, и живёт оно в
     * запросе: срок наступил, все зависимости применены, и по своей пачке операция первая из
     * незакрытых. Ожидающие, отправлявшиеся в момент смерти процесса и получившие ответ, который
     * ещё не применён. Нечитаемые строки — тоже здесь, с причиной: работник их пропускает, а
     * промах словаря дочитывает.
     */
    suspend fun ready(now: Instant): List<StoredSyncOperation>

    /**
     * Когда наступит ближайший срок незакрытой операции, ещё не наступивший к [now]; `null` — ждать
     * нечего. Срок повтора — состояние базы, а не память прохода: проход видит только то, что
     * трогал, а отложенная при старте или чужим проходом операция ждёт ровно здесь.
     */
    suspend fun nextDueAt(now: Instant): Instant?

    /** Ссылка на аптечку, которую называет снимок; `null` — локально её нет, и снимок положить некуда. */
    suspend fun medKit(id: Uuid): MedKitRef?

    /** Операция, собранная из строки, — если строка есть и читается; нечитаемые отдаёт [ready]. */
    suspend fun operation(id: Uuid): SyncOperation?

    /**
     * Пачка, какой её знает устройство, — подтверждённое состояние и знание очереди о нём: то, по
     * чему готовится запрос (PLAN E2, E3). `null` — пачки у нас нет.
     */
    suspend fun knownPackage(id: Uuid): PackageSnapshot?

    /** Кладёт прочитанный снимок поверх подтверждённого остатка и броней (PLAN E4). */
    suspend fun layDown(snapshot: PackageSnapshot, at: Instant)

    /**
     * Записывает операцию после перехода, который решила очередь, — в строку, прочитанную этой же
     * транзакцией: лежит она со статусом [was] (F5). Замороженный запрос пишется вместе с ней.
     */
    suspend fun write(operation: SyncOperation, was: SyncOperationStatus)

    /** Незакрытые операции полки [medKitId] — и читаемые, и нет: у каждой свой исход, когда полки не станет. */
    suspend fun unclosedOfMedKit(medKitId: Uuid): List<StoredSyncOperation>

    /**
     * Записывает ответ сервера до того, как он применён: полученное подтверждение не теряется,
     * даже если применить его сейчас нечем. Операция становится `ANSWERED`.
     */
    suspend fun answered(id: Uuid, answer: Receipt, at: Instant)

    /** Ответ есть, применить его пока нечем — операция остаётся `ANSWERED` до [notBefore], причина названа. */
    suspend fun defer(id: Uuid, reason: String, at: Instant, notBefore: Instant)

    /**
     * Применяет [settlement] одной транзакцией: переход строки операции и его эффекты. Что исход
     * значит, уже решено в очереди ([Delivery.settlement]); эффекты ложатся только если переход
     * изменил строку — закрытие одно.
     */
    suspend fun settle(id: Uuid, settlement: Settlement, at: Instant)

    /**
     * Ставит команду; номер выдаёт хранилище. Только внутри [transaction] с её причиной. [shelf] —
     * полка, на которой команда действует: по ней очередь держит порядок полки.
     */
    suspend fun enqueue(queued: QueuedCommand, shelf: Uuid, at: Instant): SyncOperation
}
