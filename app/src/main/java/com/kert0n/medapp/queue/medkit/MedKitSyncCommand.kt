package com.kert0n.medapp.queue.medkit

import com.kert0n.medapp.queue.Expected
import com.kert0n.medapp.queue.SyncCommand
import kotlin.uuid.Uuid

/**
 * Что предстоит доставить серверу по аптечке: сделать общей, удалить для всех, выйти.
 *
 * Слой данных по той же причине, что и команды упаковки: это доставка, а не правило о лекарстве.
 * Каталог называет понятие — аптечку, — поэтому команды о ней лежат отдельно от команд об
 * упаковке, а не вместе «по механизму».
 *
 * Корень свой, а не общий с упаковкой: Kotlin не закрывает иерархию через пакеты, и деление по
 * понятиям здесь важнее одного корня на все команды. Общий маркер `SyncCommand` появится вместе
 * с записью очереди `SyncOperation` (PLAN E2, PR 4), когда у него будет потребитель — вводить его
 * заранее значило бы завести тип без единого места, где он нужен.
 */
sealed interface MedKitSyncCommand : SyncCommand {

    val medKitId: Uuid

    /** Ответы по аптечке команде не нужны: `{id}` созданной она и так знает, остальное — `204`. */
    override val expects: Expected get() = Expected.NOTHING

    /**
     * Сделать аптечку общей: на сервере появляется её существование и участие.
     *
     * Только сама полка и ничего больше. Её содержимое едет обычными командами пачек — теми же,
     * какими местная коробка переезжает на общую полку, — и ждёт эту команду по номеру: коробку
     * некуда класть, пока полки у сервера нет (PLAN E5, E6). Название и место хранения не уезжают
     * — сервер их не хранит и не будет (PLAN C0).
     */
    data class Publish(override val medKitId: Uuid) : MedKitSyncCommand

    /**
     * Удалить аптечку для всех участников.
     *
     * [transferTo] — куда уносится содержимое: физическую аптечку унесли, а лекарства разместили в
     * другой. `null` означает удаление вместе с содержимым (PLAN E6). Два разных действия названы
     * одним видом потому, что на проводе это одна операция с параметром.
     */
    data class Delete(
        override val medKitId: Uuid,
        val transferTo: Uuid? = null
    ) : MedKitSyncCommand {
        init {
            require(transferTo != medKitId) { "содержимое не переносится в удаляемую аптечку" }
        }
    }

    /**
     * Выйти из общей аптечки.
     *
     * Сервер снимает брони каскадом по участию, источники становятся недоступны, а **курс и его
     * история остаются** (PLAN D5, E6). Это не удаление аптечки: она цела, изменился наш доступ.
     */
    data class Leave(override val medKitId: Uuid) : MedKitSyncCommand
}
