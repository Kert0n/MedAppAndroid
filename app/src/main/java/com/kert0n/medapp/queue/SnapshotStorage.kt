package com.kert0n.medapp.queue

import java.time.Instant
import kotlin.uuid.Uuid

/**
 * Что чтению полного снимка нужно от хранилища — и только это (PLAN E4). Снимок утверждает не
 * «вот что изменилось», а «вот всё, что мне доступно», поэтому кладётся он целиком и одной
 * транзакцией: половина правды противоречила бы другой половине.
 *
 * Транзакция принадлежит хранилищу, как и у очереди: сеть никогда не выполняется внутри неё (F5).
 */
interface SnapshotStorage {

    /**
     * Что у нас было к началу чтения. Спрашивается **до** сети: что человек заведёт или уберёт,
     * пока снимок летит, в ответ попасть не могло — и ни пропажей, ни появлением это не считается.
     */
    suspend fun serverKnows(): ServerKnowledge

    /**
     * Снимок в базу. Что из названного ляжет, решают версии — запоздалая половина не откатывает
     * свежую (PLAN E1), — и решает это одна дверь `PackageDao.applySnapshot`. Незнакомая полка
     * заводится, пропавшее уходит утратой доступа: коробка — своим концом со следом, полка —
     * вместе со своим содержимым. Убранного, пока снимок летел, он не возвращает.
     *
     * [at] — момент наблюдения: им датируется первое знакомство с полкой и чужой коробкой.
     */
    suspend fun lay(snapshot: ServerSnapshot, at: Instant)

    /**
     * Коробки одной полки, о которых сервер знает и ждать по ним нечего. Нужны перечитыванию
     * полки: оно утверждает о ней целиком — коробка, которой полка не назвала, у нас кончается, —
     * но о чужих полках не говорит ничего (PLAN E4).
     */
    suspend fun packagesKnownOn(medKitId: Uuid): Set<Uuid>
}

/**
 * Полки и коробки к началу чтения. Вопросов к ним два, и ответы разные:
 *
 * - [medKits], [packages] — о чём сервер знал и по чему нечего ждать: их отсутствие в снимке
 *   значит утрату доступа. Неотправленное и помеченное сюда не входит — их отсутствие объяснит
 *   ответ на их же команду;
 * - [heldMedKits], [heldPackages] — что у нас вообще было: полка, которой среди них нет, в снимке
 *   появилась, а вещь, которая была и которой к укладке не стало, убрана, пока снимок летел, и
 *   запоздавший снимок её не возвращает (PLAN C0).
 */
class ServerKnowledge(
    medKits: Set<Uuid>,
    packages: Set<Uuid>,
    heldMedKits: Set<Uuid>,
    heldPackages: Set<Uuid>
) {
    val medKits: Set<Uuid> = medKits.toSet()
    val packages: Set<Uuid> = packages.toSet()
    val heldMedKits: Set<Uuid> = heldMedKits.toSet()
    val heldPackages: Set<Uuid> = heldPackages.toSet()
}
