package com.kert0n.medapp.network.account

/**
 * Вернуть серверу учётку, которую он забыл: зарегистрировать **те же** логин и пароль (PLAN B1, G2;
 * решение владельца 2026-09-23). `true` — сервер снова знает эту учётку, и пропуск по ней можно
 * просить заново. Сохранённое на устройстве при этом не пишется: данные те же, что лежат.
 *
 * Отдельный порт, а не вызов регистрации: выдача пропуска живёт в клиенте, через который
 * регистрация сама и ходит, и знать её напрямую выдача не может.
 */
fun interface AccountReclaim {

    suspend fun reclaim(account: AccountCredentials): Boolean

    companion object {
        /** Возвращать некому — пробы и проверки, где учётку ведёт не приложение. */
        val None: AccountReclaim = AccountReclaim { false }
    }
}
