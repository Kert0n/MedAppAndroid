package com.kert0n.medapp.network.crpt

import com.kert0n.medapp.domain.value.DosageForm
import com.kert0n.medapp.domain.value.Vocabulary

/**
 * Чужой текст о форме — к базовому виду сервера (PLAN H5).
 *
 * Реестр называет форму подробно и по-своему: «ТАБЛЕТКА, ПОКРЫТАЯ ПЛЁНОЧНОЙ ОБОЛОЧКОЙ»,
 * «р-р д/в/в», «капс.». Подробности применения и дозировка вида не меняют: таблетка, покрытая
 * оболочкой, — те же таблетки.
 *
 * Правило то же, каким сервер сворачивал свой каталог, — **первое слово названия**: семнадцать
 * распространённых видов остаются собой, двадцать шесть редких сводятся к «другие» (issue #36).
 * Сверх серверного здесь только то, чего в каталоге не было: падежи («таблетка»), мягкий знак
 * («мазь») и сокращения реестра. Совпадение свёрток держит таблица ожиданий из всех 208 прежних
 * подробных названий (`CrptFormMapperTest`): разойдись они — человек выбрал бы одну форму, а в
 * каталоге сервера лекарство лежало бы под другой.
 *
 * Объект берётся **из снимка сервера** по имени: тождество формы — серверный `id`, и придумать
 * его клиенту нечем. Текст не узнан или такой формы в снимке нет — `null`, а сам текст остаётся
 * у предложения (`formText`), и человек выберет сам.
 */
internal object CrptFormMapper {

    /** Косая черта делит альтернативы («капсулы/таблетки»): берётся первая узнанная. */
    fun resolve(text: String, vocabulary: Vocabulary): DosageForm? =
        text.lowercase().replace('ё', 'е').split('/').firstNotNullOfOrNull { alternative ->
            val word = FIRST_WORD.find(alternative.trimStart())?.value?.replace("ь", "")
            word?.let(::baseName)?.let(vocabulary::formWithName)
        }

    /** Какой вид назван словом: сокращение раскрывается, остальное узнаётся по началу слова. */
    private fun baseName(word: String): String? = ABBREVIATIONS[word]
        ?: COMMON_ROOTS.firstOrNull { (root, _) -> word.startsWith(root) }?.second
        ?: OTHER.takeIf { OTHER_ROOTS.any(word::startsWith) }

    /** Первое слово — и только оно: дальше идут применение и дозировка, а не вид. */
    private val FIRST_WORD = Regex("^[а-я]+(?:-[а-я]+)?")

    private const val OTHER = "другие"

    /** Сокращения реестра: в каталоге сервера их не было, а в ответах «Честного знака» есть. */
    private val ABBREVIATIONS = mapOf(
        "р-р" to "раствор", "табл" to "таблетки", "таб" to "таблетки",
        "капс" to "капсулы", "сусп" to "суспензия", "супп" to "суппозитории",
        "пор" to "порошок", "гран" to "гранулы", "лиоф" to "лиофилизат",
        "конц" to "концентрат"
    )

    /**
     * Семнадцать распространённых видов — началом слова: приходят они в разных падежах и
     * числах («таблетка», «таблетки», «таблеток»).
     */
    private val COMMON_ROOTS = listOf(
        "аэрозол" to "аэрозоль", "гел" to "гель", "гранул" to "гранулы",
        "капл" to "капли", "капсул" to "капсулы", "концентрат" to "концентрат",
        "крем" to "крем", "лиофилизат" to "лиофилизат", "маз" to "мазь",
        "настойк" to "настойка", "порош" to "порошок", "раствор" to "раствор",
        "сироп" to "сироп", "спре" to "спрей", "суппозитор" to "суппозитории",
        "суспенз" to "суспензия", "таблет" to "таблетки"
    )

    /**
     * Двадцать шесть редких видов прежнего каталога — все они и на сервере стали «другие».
     * Мягкий знак снят заранее, поэтому «бальзам» ищется как «балзам».
     */
    private val OTHER_ROOTS = listOf(
        "жидкост", "эмулс", "экстракт", "масл", "пластыр", "драже", "эликсир",
        "пастил", "имплантат", "шампун", "паста", "линимент", "лак", "сбор",
        "балзам", "пленк", "сок", "пен", "систем", "газ", "губк", "дисперс",
        "карандаш", "пилюл", "плитк", "резинк"
    )
}
