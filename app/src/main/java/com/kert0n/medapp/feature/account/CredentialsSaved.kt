package com.kert0n.medapp.feature.account

/**
 * Легла ли запись учётки на устройство. Случая два, и дальше делается разное: [SAVED] — можно
 * регистрироваться и работать; [LOST] — записать не удалось, и, поскольку данные придумывались до
 * запроса, на сервере ничего не заведено: терять нечего, повторить можно (PLAN G2).
 *
 * Поэтому запись не бросает: несохранённая учётка — это исход настройки, о котором говорят
 * человеку, а не сбой, от которого отмахиваются повтором.
 */
enum class CredentialsSaved { SAVED, LOST }
