package com.kert0n.medapp.feature

/**
 * Правило F5 одним местом: что прочитано этой же транзакцией, никуда не делось. Условная
 * запись по прочитанному — по редакции, по пометке, по владельцу — даёт строку, а повторное
 * чтение — значение. Ноль строк или `null` здесь не гонка (внутри транзакции её нет), а ошибка
 * сценария: писали не то, что читали, — и она называется по имени, а не молчит.
 *
 * [subject] — что читали: «пачка», «план», «аптечка», «запись эпизода».
 */
fun Boolean.readThisTransaction(subject: String) {
    check(this) { "$subject есть в этой же транзакции — условная запись не даёт ноль строк" }
}

/** То же для чтения: прочитанное или только что записанное этой же транзакцией находится. */
fun <T : Any> T?.readThisTransaction(subject: String): T =
    checkNotNull(this) { "$subject есть в этой же транзакции — чтение не даёт null" }
