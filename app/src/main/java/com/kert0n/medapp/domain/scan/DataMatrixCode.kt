package com.kert0n.medapp.domain.scan

/**
 * DataMatrix «Честного знака» — текст, который отдал сканер (PLAN H5). Код **не разбирается и не
 * нормализуется**: он несёт крипто-хвост, расшифровывать его нечем, а о циклах обновления чужого
 * API мы не знаем ничего — поэтому в CRPT он уходит **байт в байт**, разделители GS (`U+001D`)
 * между полями `91`/`92` остаются на месте. Единственная правка — префикс `{FNC1}` в [wire]:
 * литерал из шести символов, а не управляющий байт. Правило держит тест тела запроса.
 */
data class DataMatrixCode(val text: String) {

    init {
        require(text.isNotEmpty()) { "код с коробки не бывает пустым" }
    }

    /** Что уходит в поле `code` запроса — текст как есть под литеральным `{FNC1}`. */
    val wire: String get() = FNC1 + text

    companion object {
        const val FNC1 = "{FNC1}"
    }
}
