package com.kert0n.medapp.domain.notification

import java.time.Duration

/**
 * Свежесть перед разговором с человеком (PLAN D8, E4): подождать заход не дольше [within] и
 * показать то, что есть. Приёму свежесть не нужна — расход уезжает очередью, которая читает пачку
 * перед отправкой; нужна она тому, что человек **видит** в карточке: остатку и тому, есть ли ещё
 * коробка.
 *
 * Названо портом, потому что владелец доставки знает «подожди немного», а не «сходи в очередь за
 * снимком»: как устроен заход, ему знать незачем.
 */
interface Freshness {

    suspend fun refreshBriefly(within: Duration)
}
