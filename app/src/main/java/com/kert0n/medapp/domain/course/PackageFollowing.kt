package com.kert0n.medapp.domain.course

import java.time.Instant
import kotlin.uuid.Uuid

/**
 * Коробка изменилась — лечение следует за ней (PLAN D5). Действие названо доменом, а исполняет его
 * прикладной владелец (`feature/course/CourseFollowing`): кто бы коробку ни изменил — человек
 * пересчётом, сосед снимком, сервер ответом на команду, — следствие для курса одно и то же и
 * считается одним местом, внутри той транзакции, где коробка изменилась (E4, F5). Хранение даёт
 * транзакцию и зовёт порт; что именно следует, порт не рассказывает.
 */
interface PackageFollowing {

    /** Коробка [packageId] изменилась в момент [at]: каждое лечение, держащее её, следует за ней. */
    suspend fun follow(packageId: Uuid, at: Instant)
}
