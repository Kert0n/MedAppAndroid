package com.kert0n.medapp.domain.intake

/**
 * Отказ записать приём — обычный ответ внутри `Result`, а не сбой. Текста нет: сообщение по
 * [reason] берёт экран из `R.string.*` (PLAN H1).
 */
class IntakeRejected(val reason: Reason) : IllegalStateException(reason.name) {

    /** Причины различаются, потому что ведут человека к разным действиям. */
    enum class Reason {

        /** Эпизод закрыт: его план ответов не принимает; приём после закрытия — внеплановый факт. */
        EPISODE_CLOSED,

        /** Пачки больше нет: кончилась, выброшена или доступ к ней утрачен (PLAN D3). */
        PACKAGE_UNUSABLE,

        /** Единица дозы — не та, в которой пачку считают сейчас. */
        UNIT_MISMATCH,

        /**
         * В своей коробке меньше, чем принято: местный остаток списать не из чего. У коробки на
         * полке, отвечающей серверу, истина по количеству — сервер, и нехватку отвечает он (E3).
         */
        INSUFFICIENT,

        /**
         * Пачка не из источников курса: такой приём — внеплановый факт, и пункт курса им не
         * закрывается (PLAN D5). Человека ведёт к другому действию, поэтому причина своя.
         */
        PACKAGE_NOT_A_SOURCE
    }
}
