package com.kert0n.medapp.domain.pack

/**
 * Конец жизни коробки — событие, а не отсутствие строки: у него есть то, что остаётся навсегда
 * ([record]), и зависимые, которые о нём узнают, — курсы, державшие коробку источником.
 *
 * Значение целиком: хранение получает его одной дверью и одной транзакцией снимает источник у
 * курса и убирает строку — порознь этого не бывает (PLAN D3, F5). Собрать конец мимо переходов
 * [Package] нечем, поэтому убрать коробку, не спросив её саму, не выражается.
 */
class PackageEnding internal constructor(val pkg: Package) {

    /** Вечная запись о коробке: за неё держатся приёмы, и конец она переживает (D3, D6). */
    val record: PackageRecord get() = pkg.record

    override fun toString(): String = "PackageEnding(pkg=${pkg.id})"
}
