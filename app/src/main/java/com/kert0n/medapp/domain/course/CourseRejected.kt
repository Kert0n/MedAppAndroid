package com.kert0n.medapp.domain.course

/**
 * Отказ курса в действии человека — обычный ответ внутри `Result`, а не сбой. Текста в нём нет:
 * сообщение по [reason] берёт экран из `R.string.*` (PLAN H1).
 */
class CourseRejected(val reason: Reason) : IllegalStateException(reason.name) {

    /** Причины различаются, потому что ведут человека к разным действиям. */
    enum class Reason {

        /** Коробка помечена — её выбрасывают или из её полки ушли: источником она не бывает. */
        PACKAGE_UNUSABLE,

        /** Пачка уже в препарате курса. */
        ALREADY_ATTACHED,

        /** У пачки не заполнена форма, и нельзя сказать, тот ли это препарат (PLAN D5). */
        FORM_UNKNOWN,

        /** Форма пачки отличается от назначенной. */
        FORM_MISMATCH,

        /** Единица пачки отличается от единицы назначенной дозы. */
        UNIT_MISMATCH,

        /** Активировать нельзя: нет расписания. */
        SCHEDULE_MISSING,

        /** Разовая доза не названа: ни активировать, ни сверить с ней пачку. */
        DOSE_MISSING,

        /** Форма лечения не названа: ни активировать, ни сверить с ней пачку. */
        FORM_MISSING,

        /** Активировать нельзя: не названо, сколько всего доз, — или названо ноль. */
        TOTAL_DOSES_MISSING,

        /** Новое расписание начинается раньше сегодняшнего дня: пункты в прошлом не заводят. */
        SCHEDULE_IN_PAST
    }
}
