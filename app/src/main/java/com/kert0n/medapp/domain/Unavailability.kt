package com.kert0n.medapp.domain

/**
 * Почему действие не вышло сейчас. Значение, а не текст: текстов для человека в домене нет, их
 * берёт экран из `R.string.*`.
 *
 * Случаи различаются тем, что человек делает дальше: связи нет — повторить, когда появится;
 * сервер промолчал — повторить позже; сервер нас не принял — повтор тем же не поможет, нужно
 * решение; устройство не записало или не прочитало — повторить, но причина не серверная, и сказать
 * надо другое.
 *
 * Кодов ответа и причин отказа сети здесь нет по определению: домен не знает, что где-то есть
 * HTTP, — он знает, что действию нужен сервер и сервера сейчас нет (PLAN C3).
 */
enum class Unavailability {
    NO_CONNECTION,
    SERVER_SILENT,
    SERVER_REFUSED_US,
    DEVICE_STORAGE
}
