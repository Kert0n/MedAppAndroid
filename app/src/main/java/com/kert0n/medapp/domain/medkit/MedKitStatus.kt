package com.kert0n.medapp.domain.medkit

/**
 * Решение человека об аптечке, которое ещё не подтвердили (PLAN E5, E6). Лежит на самой аптечке и
 * меняется её переходами; статусы коробок на ней — их собственные.
 */
enum class MedKitStatus {

    /** Ничего не решено сверх подтверждённого. */
    ACTIVE,

    /** Публикация стоит в очереди: аптечкой пользуются, и отвечает она уже серверу. */
    PUBLISHING,

    /** Аптечку убирают из моего списка: видна, но выведена из оборота до ответа. */
    REMOVING;

    /** Можно ли класть в неё коробки и менять её сведения. */
    val allowsUse: Boolean get() = this != REMOVING

    /** Можно ли принять о ней новое решение — убрать или опубликовать. Одно решение за раз. */
    val allowsDecision: Boolean get() = this == ACTIVE
}
