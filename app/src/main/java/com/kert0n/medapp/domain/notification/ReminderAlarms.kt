package com.kert0n.medapp.domain.notification

import java.time.Instant

/**
 * Разбудить процесс к моменту — и только это (PLAN D8). Постановок **две**: точная и
 * приблизительная — это разные просьбы к системе, и одна другую не заменяет: приблизительную
 * система вправе задержать на минуты, а точный срок приёма ждать её не должен. У каждой точности
 * своя постановка, и повтор переставляет её же; расписание целиком лежит в обязательствах, а
 * система остаётся исполнителем ближайшего срока каждой точности. Точно — если она разрешила;
 * иначе примерно, и [canBeExact] говорит об этом честно.
 *
 * О ключах, видах и приёмах порт не знает и показывать ничего не умеет: что сказать проснувшись —
 * забота владельца доставки.
 */
interface ReminderAlarms {

    val canBeExact: Boolean

    /** Разбудить к [at] постановкой названной точности. Повторный вызов переставляет её же. */
    suspend fun wakeAt(at: Instant, exact: Boolean)

    /** Будить этой точностью незачем: обязательств, которые её просят, не осталось. */
    suspend fun stopWaking(exact: Boolean)
}
