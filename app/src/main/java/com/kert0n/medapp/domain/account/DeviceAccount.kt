package com.kert0n.medapp.domain.account

/**
 * Учётная запись этого устройства на сервере. Правило продукта: без неё общего нет вовсе, и
 * знакомство с сервером — такое же действие, как остальные, а не подробность провода (PLAN B1, G2).
 *
 * **Как** устройство знакомится — придуманные им логин и пароль, записанные до запроса, повтор
 * теми же данными после потерянного ответа — ведёт сценарий регистрации. Домен называет само
 * действие и его исходы, и ими говорят все остальные.
 */
interface DeviceAccount {

    /** Учётная запись есть или заводится; повтор безопасен и второй записи не создаёт. */
    suspend fun ensure(): AccountReadiness

    /**
     * Решение человека о нечитаемой учётке (PLAN G2): сохранённое, которое не открыть, оставляется,
     * и заводится новая — обычным знакомством. Читаемую учётку не трогает: решать тут нечего, и
     * повтор после потерянного ответа идёт теми же придуманными данными, а не третьими.
     */
    suspend fun replaceUnreadable(): AccountReadiness
}
