package com.kert0n.medapp.domain.pack

/**
 * Решение человека о коробке, которое ещё не подтвердили (PLAN E1, E6). Статус лежит на самой
 * коробке и меняется её переходами: сценарий ставит его вместе с командой, ответ сервера доводит
 * решение до конца либо снимает пометку.
 *
 * Это не состояние жизни коробки: строка есть — коробка у меня, кончившаяся строки не оставляет.
 * Статус говорит только о том, что решено и ждёт согласия полки, и о том, чем пока можно
 * пользоваться. Что он значит для доставки, коробка не знает.
 */
enum class PackageStatus {

    /** Ничего не решено сверх подтверждённого. */
    ACTIVE,

    /** Изменение записано и ждёт полки: коробкой пользуются как обычно. */
    CHANGING,

    /** Человек решил её выбросить: видна, но выведена из оборота до ответа. */
    REMOVING,

    /** Из полки вышли: коробка цела, но уже не у нас — видна, трогать нельзя до ответа. */
    LOST;

    /** Можно ли брать из коробки, править её, переносить и назначать источником курса. */
    val allowsUse: Boolean get() = this == ACTIVE || this == CHANGING
}
