package com.kert0n.medapp.domain.notification

/**
 * Показать человеку — действие продукта, названное доменом и исполненное платформой (PLAN D8, H1).
 * Как оно выглядит и на каком канале звучит, домен не знает.
 */
interface Notifier {

    /**
     * Сказать обязательство о его [subject]. Предмета нет — повода больше нет; но разрешение
     * спрашивается раньше: непоказуемое ждёт, а не забывается.
     */
    suspend fun show(reminder: Reminder, subject: ReminderSubject?): Delivery

    suspend fun dismiss(key: NotificationKey)
}

/**
 * Чем кончился показ (PLAN D8, C1). Четыре случая, потому что поведение различает четыре: у одного
 * обязательство исполнено, у другого ждёт человека, у третьего повода больше нет, у четвёртого —
 * повторяем. Пока это был `Boolean`, три последних были неразличимы: будильник вставал на
 * прошедший срок, и устройство будилось без конца.
 */
enum class Delivery {

    /** Сказано. */
    SHOWN,

    /** Показать нечем: разрешения нет или уведомления выключены. Обязательство ждёт (H3 №29). */
    NOT_ALLOWED,

    /** Повода больше нет: коробки или курса, о которых говорить, не нашлось. */
    SUBJECT_GONE,

    /** Сбой базы или системы: повод жив, и мы вернёмся через задержку. */
    FAILED
}
